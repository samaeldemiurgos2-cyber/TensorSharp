#!/usr/bin/env python3
"""Reproducible, synthetic Qwen3.8 long-context/agent HTTP replay.

Prepare once, replay the same JSONL against each binary/configuration. This is
not the private screenshot workload. Histories are prescribed, not generated by
the measured engine. Every lane executes its steps sequentially; lanes start
together. TTFT includes preprocessing, queueing, prefill and streaming transport.
Only the prepare command requires Pillow. Reports belong in ignored evidence.
"""
from __future__ import annotations

import argparse
import base64
from collections import Counter
from concurrent.futures import ThreadPoolExecutor
import hashlib
import http.client
import io
import json
import math
from pathlib import Path
import statistics
import threading
import time
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[2]


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, ensure_ascii=False,
                                     separators=(",", ":")).encode()).hexdigest()


def evidence_path(value):
    path = Path(value).resolve()
    if not any(path.is_relative_to(ROOT / folder) for folder in ("artifacts", "docs/validation")):
        raise argparse.ArgumentTypeError("Use ignored artifacts/ or docs/validation/ in this checkout")
    path.parent.mkdir(parents=True, exist_ok=True)
    return path


def padding(tokens):
    # These words are each one Qwen token including the preceding space. The
    # actual prompt token count (including template/tools/media) comes from usage.
    words = (" tree river cloud garden stone ocean window road green book" * (tokens // 10 + 1)).split()
    return " ".join(words[:tokens])


def card(code, color, width=1344, height=768):
    from PIL import Image, ImageDraw, ImageFont
    path = next((p for p in ("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
                            "/System/Library/Fonts/Supplemental/Arial Bold.ttf") if Path(p).exists()), None)
    font_size = max(8, round(90 * min(width / 672, height / 504)))
    font = ImageFont.truetype(path, font_size) if path else ImageFont.load_default(size=font_size)
    image = Image.new("RGB", (width, height), "white")
    draw = ImageDraw.Draw(image)
    draw.text((width / 2, height * 130 / 504), str(code), font=font, fill="black", anchor="mm")
    draw.rectangle((width * 100 / 672, height * 250 / 504,
                    width * 572 / 672, height * 420 / 504), fill=color)
    stream = io.BytesIO()
    image.save(stream, format="PNG")
    return "data:image/png;base64," + base64.b64encode(stream.getvalue()).decode()


def tools34():
    tools = [{"type": "function", "function": {
        "name": "submit_observation", "description": "Report the current screenshot's code and rectangle color.",
        "parameters": {"type": "object", "properties": {
            "code": {"type": "string"}, "color": {"type": "string"}},
            "required": ["code", "color"], "additionalProperties": False}}}]
    for i in range(33):
        tools.append({"type": "function", "function": {
            "name": f"desktop_action_{i:02}",
            "description": f"Desktop action {i}. Available for unrelated future tasks; do not call for observation.",
            "parameters": {"type": "object", "properties": {
                "target": {"type": "string"}, "value": {"type": "string"}},
                "required": ["target"]}}})
    return tools


def prepare(args):
    if min(args.steps, args.lanes, args.max_tokens, args.image_width, args.image_height) < 1:
        raise ValueError("steps, lanes, max-tokens and image dimensions must be positive")
    rows = []
    def add(scenario, lane, step, messages, expected=None, tools=None):
        body = {"messages": messages, "stream": True, "stream_options": {"include_usage": True},
                "temperature": 0, "repeat_penalty": 1, "think": False,
                "enable_thinking": False, "chat_template_kwargs": {"enable_thinking": False},
                "max_tokens": args.max_tokens, "skills": [], "skills_discovery": False, "multi_agent": False}
        if tools:
            body["tools"] = tools
            body["tool_choice"] = "auto"
        images = []
        for message in messages:
            if isinstance(message.get("content"), list):
                for part in message["content"]:
                    if part.get("type") == "image_url":
                        image_bytes = base64.b64decode(part["image_url"]["url"].split(",", 1)[1], validate=True)
                        images.append({"sha256": hashlib.sha256(image_bytes).hexdigest(),
                                       "width": args.image_width, "height": args.image_height})
        rows.append({"scenario": scenario, "lane": lane, "step": step, "body": body,
                     "expected": expected, "images": images, "request_sha256": digest(body)})
    instruction = "The following neutral words are padding for a latency test. Ignore them and answer the last user request.\n"
    question = "Explain how a bicycle works, including steering, balance, gears and brakes, in clear English."
    for lane in range(args.lanes):
        for name, count in (("short1k", 1000), ("prefill8k", 8000), ("repeat19k", 19000)):
            messages = [{"role": "system", "content": f"Workload {name}, lane {lane}. " + instruction + padding(count)},
                        {"role": "user", "content": question}]
            for step in range(3):
                add(name, lane, step, messages)
        messages = [{"role": "system", "content": f"Incremental lane {lane}. " + instruction + padding(16500)},
                    {"role": "user", "content": padding(2400) + "\n" + question}]
        add("incremental", lane, 0, messages)
        # Deliberately prescribed history: comparable even if answers drift.
        for step in range(1, 4):
            messages = messages + [{"role": "assistant", "content": "A bicycle uses pedals, gears, wheels and brakes."},
                                   {"role": "user", "content": padding(2450) + "\n" + question}]
            add("incremental", lane, step, messages)
        def observation(step, base=4821):
            return {"code": str(base + lane * 113 + step * 7),
                    "color": ("red", "blue", "green", "yellow")[(step + lane) % 4]}
        observations = [observation(step) for step in range(args.steps)]
        screenshots = [card(item["code"], item["color"], args.image_width, args.image_height) for item in observations]
        def screenshot_turn(step):
            return {"role": "user", "content": [
                {"type": "text", "text": f"Step {step}: report the code and color in this current screenshot using submit_observation."},
                {"type": "image_url", "image_url": {"url": screenshots[step]}}]}
        for step in range(args.steps):
            # Stable long system + changing bounded conversation and screenshot.
            # Six retained turns model a rolling CUA history without exceeding 32K.
            messages = [{"role": "system", "content": f"Desktop observation lane {lane}. " + instruction + padding(14000)
                         + "\nRead the latest screenshot only. Call submit_observation exactly once with its four-digit code and color. Do not write prose."}]
            for old in range(max(0, step - 6), step):
                messages.extend([
                    screenshot_turn(old),
                    {"role": "assistant", "content": "", "tool_calls": [{"id": f"call_{old}", "type": "function",
                        "function": {"name": "submit_observation", "arguments": json.dumps(observations[old])}}]},
                    {"role": "tool", "tool_call_id": f"call_{old}", "content": "Observation saved. " + padding(150)}])
            messages.append(screenshot_turn(step))
            add("agent34", lane, step, messages, observations[step], tools34())
        # Replacing only the newest image measures the reusable checkpoint before
        # media. In contrast, agent34 retains prior images until its rolling trim;
        # after trimming, its common prefix can fall back to the system/tool prefix.
        for step in range(3):
            expected = observation(step, base=6851)
            messages = [{"role": "system", "content": f"Image replacement lane {lane}. " + instruction + padding(14000)
                         + "\nRead the latest screenshot only. Call submit_observation exactly once with its four-digit code and color. Do not write prose."},
                        {"role": "user", "content": [
                            {"type": "text", "text": "Report the code and color in the current screenshot using submit_observation."},
                            {"type": "image_url", "image_url": {"url": card(expected["code"], expected["color"], args.image_width, args.image_height)}}]}]
            add("image_replace", lane, step, messages, expected, tools34())
        add("arithmetic", lane, 0, [{"role": "user", "content": "Only output the integer result: 123 + 456."}], {"answer": "579"})
    with args.output.open("w") as target:
        for row in rows:
            target.write(json.dumps(row, ensure_ascii=False) + "\n")
    unique_images = {image["sha256"]: image for row in rows for image in row["images"]}
    manifest = {"path": str(args.output), "requests": len(rows), "sha256": hashlib.sha256(args.output.read_bytes()).hexdigest(),
                "scenario_counts": dict(Counter(row["scenario"] for row in rows)),
                "image_width": args.image_width, "image_height": args.image_height,
                "image_token_target": args.image_width * args.image_height // 1024
                    if args.image_width % 32 == 0 and args.image_height % 32 == 0 else None,
                "image_token_assumption": "patch_size=16, spatial_merge=2, no resize. Verify actual engine expansion; this is a target, not observed usage.",
                "images": [unique_images[key] for key in sorted(unique_images)]}
    manifest_path = args.output.with_suffix(".manifest.json")
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps({key: value for key, value in manifest.items() if key != "images"} | {"manifest": str(manifest_path)}))


def validate_result(result, expected):
    failures = []
    if result.get("http_status") != 200:
        failures.append("missing/non-success HTTP status")
    if not result.get("done") or not result.get("finish_reason"):
        failures.append("incomplete stream")
    elif result["finish_reason"] not in ("stop", "length", "tool_calls"):
        failures.append("unexpected finish reason")
    if result.get("errors"):
        failures.extend(result["errors"])
    if result.get("reasoning") or any(marker in result.get("answer", "") for marker in ("<think>", "</think>")):
        failures.append("unexpected reasoning output")
    if type(result.get("completion_tokens")) is not int or result["completion_tokens"] < 1:
        failures.append("missing/empty completion usage")
    if type(result.get("prompt_tokens")) is not int or result["prompt_tokens"] < 1:
        failures.append("missing/empty prompt usage")
    details = result.get("prompt_tokens_details")
    if details is not None and not isinstance(details, dict):
        failures.append("invalid prompt token details")
    elif isinstance(details, dict) and details.get("cached_tokens") is not None:
        cached = details["cached_tokens"]
        if (type(cached) is not int or cached < 0 or
                (type(result.get("prompt_tokens")) is int and cached > result["prompt_tokens"])):
            failures.append("invalid cached token usage")
    if expected:
        if "answer" in expected:
            if result.get("answer", "").strip() != expected["answer"]:
                failures.append("incorrect arithmetic answer")
            if result.get("finish_reason") != "stop" or result.get("tool_calls"):
                failures.append("arithmetic answer did not finish normally")
        else:
            calls = result.get("tool_calls", [])
            if len(calls) != 1 or calls[0].get("function", {}).get("name") != "submit_observation":
                failures.append("expected exactly one submit_observation call")
            else:
                try:
                    arguments = json.loads(calls[0]["function"]["arguments"])
                    if arguments != expected:
                        failures.append("incorrect screenshot observation")
                except (KeyError, TypeError, ValueError):
                    failures.append("invalid tool arguments")
            if result.get("finish_reason") != "tool_calls":
                failures.append("incorrect tool finish reason")
            if result.get("answer", "").strip():
                failures.append("unexpected prose before tool call")
    elif not result.get("answer", "").strip():
        failures.append("empty prose answer")
    elif result.get("tool_calls"):
        failures.append("unexpected tool call in prose task")
    return failures


def has_model_delta(delta):
    if any(delta.get(key) for key in ("content", "reasoning_content", "reasoning")):
        return True
    # A server can announce a tool-call id/index before the model produces the
    # function name or arguments. That announcement is not a generated token.
    return any(any(piece.get("function", {}).get(key) for key in ("name", "arguments"))
               for piece in delta.get("tool_calls", []))


def request(url, model, row, timeout):
    address = urlsplit(url)
    cls = http.client.HTTPSConnection if address.scheme == "https" else http.client.HTTPConnection
    connection = cls(address.hostname, address.port, timeout=timeout)
    body = dict(row["body"], model=model)
    result = {key: row[key] for key in ("scenario", "lane", "step", "request_sha256", "expected")}
    result.update(answer="", reasoning="", tool_calls=[], events=[], errors=[], done=False, ttft_ms=None,
                  last_model_delta_ms=None, nonempty_delta_count=0, content_delta_count=0,
                  wire_request_sha256=digest(body))
    calls = {}
    started = time.perf_counter()
    try:
        connection.request("POST", address.path.rstrip("/") + "/v1/chat/completions",
                           json.dumps(body, ensure_ascii=False).encode(), {"Content-Type": "application/json"})
        response = connection.getresponse()
        result["http_status"] = response.status
        if response.status != 200:
            raise ValueError(f"HTTP {response.status}: {response.read()[:2048]!r}")
        if "text/event-stream" not in response.getheader("Content-Type", ""):
            raise ValueError("missing SSE content type")
        for line in response:
            if time.perf_counter() - started > timeout:
                raise TimeoutError("request deadline exceeded")
            if not line.startswith(b"data:"):
                continue
            raw = line[5:].strip()
            if not raw:
                continue
            elapsed = (time.perf_counter() - started) * 1000
            if raw == b"[DONE]":
                result["done"] = True
                break
            event = json.loads(raw)
            result["events"].append({"elapsed_ms": elapsed, "data": event})
            if event.get("error"):
                result["errors"].append(str(event["error"]))
            if event.get("usage"):
                for key in ("prompt_tokens", "completion_tokens", "total_tokens", "prompt_tokens_details", "completion_tokens_details"):
                    if key in event["usage"]:
                        result[key] = event["usage"][key]
            for choice in event.get("choices", []):
                if choice.get("index", 0) != 0:
                    raise ValueError("unexpected additional completion choice")
                if choice.get("finish_reason"):
                    result["finish_reason"] = choice["finish_reason"]
                delta = choice.get("delta", {})
                if has_model_delta(delta):
                    if result["ttft_ms"] is None:
                        result["ttft_ms"] = elapsed
                    result["last_model_delta_ms"] = elapsed
                    result["nonempty_delta_count"] += 1
                if delta.get("content"):
                    result["content_delta_count"] += 1
                result["answer"] += delta.get("content") or ""
                result["reasoning"] += delta.get("reasoning_content") or delta.get("reasoning") or ""
                for piece in delta.get("tool_calls", []):
                    call = calls.setdefault(piece.get("index", 0), {"type": "function", "function": {"name": "", "arguments": ""}})
                    if piece.get("id"):
                        call["id"] = piece["id"]
                    for key in ("name", "arguments"):
                        call["function"][key] += piece.get("function", {}).get(key) or ""
        result["tool_calls"] = [calls[index] for index in sorted(calls)]
    except Exception as error:
        result["errors"].append(str(error))
    finally:
        result["e2e_ms"] = (time.perf_counter() - started) * 1000
        connection.close()
    details = result.get("prompt_tokens_details")
    result["cached_tokens"] = details.get("cached_tokens") if isinstance(details, dict) else None
    if (type(result.get("prompt_tokens")) is int and type(result["cached_tokens"]) is int
            and 0 <= result["cached_tokens"] <= result["prompt_tokens"]):
        result["prefilled_tokens"] = result["prompt_tokens"] - result["cached_tokens"]
    # A tool parser often buffers the COMPLETE call before emitting a delta. Its
    # post-first-delta interval is then just transport overhead, not decoding.
    # The same limitation applies to a prose response emitted in one chunk.
    result["post_first_delta_tokens_per_second"] = None
    result["rate_unavailable_reason"] = None
    if result["tool_calls"]:
        result["rate_unavailable_reason"] = "tool-call deltas may be buffered until the complete call is parsed"
    elif result["content_delta_count"] < 2:
        result["rate_unavailable_reason"] = "fewer than two nonempty content deltas"
    elif result["ttft_ms"] is not None and type(result.get("completion_tokens")) is int and result["completion_tokens"] > 1:
        result["post_first_delta_tokens_per_second"] = (result["completion_tokens"] - 1) * 1000 / max(.001, result["e2e_ms"] - result["ttft_ms"])
    result["failures"] = validate_result(result, row.get("expected"))
    result["output_truncated"] = result.get("finish_reason") == "length"
    result["validation_scope"] = "exact expected output" if row.get("expected") else "stream, usage and nonempty prose only; semantic answer quality not scored"
    return result


def quantile(values, q):
    values = sorted(values)
    return values[max(0, math.ceil(len(values) * q) - 1)] if values else None


def summarize(rows, elapsed=None):
    good = [r for r in rows if not r["failures"]]
    result = {"requests": len(rows), "passed": len(good), "failed": len(rows) - len(good),
              "all_requests_valid": bool(rows) and len(good) == len(rows),
              "finish_reasons": dict(Counter(r.get("finish_reason", "missing") for r in rows)),
              "truncated": sum(r.get("finish_reason") == "length" for r in rows),
              "exact_output_checks": sum(bool(r.get("expected")) for r in rows)}
    if elapsed is not None:
        result.update(wall_seconds=elapsed,
                      throughput_tokens_per_second=sum(r.get("completion_tokens", 0) for r in good) / max(.001, elapsed))
    for key in ("e2e_ms", "ttft_ms", "post_first_delta_tokens_per_second", "prompt_tokens", "cached_tokens", "prefilled_tokens"):
        values = [r[key] for r in good if isinstance(r.get(key), (int, float))]
        result[key] = {"p50": statistics.median(values) if values else None, "p90": quantile(values, .9)}
    return result


def run(args):
    rows = [json.loads(line) for line in args.fixture.read_text().splitlines() if line]
    for row in rows:
        if digest(row["body"]) != row["request_sha256"]:
            raise ValueError("fixture request digest mismatch")
    scenarios = args.scenarios.split(",")
    degrees = [int(x) for x in args.concurrency.split(",")]
    if not degrees or min(degrees) < 1 or len(degrees) != len(set(degrees)):
        raise ValueError("concurrency must contain unique positive degrees")
    if len(scenarios) != len(set(scenarios)):
        raise ValueError("scenarios must be unique")
    if args.steps is not None and args.steps < 1:
        raise ValueError("steps must be positive")
    if args.timeout <= 0:
        raise ValueError("timeout must be positive")
    identities = [(r["scenario"], r["lane"], r["step"]) for r in rows]
    if len(identities) != len(set(identities)):
        raise ValueError("duplicate scenario/lane/step in fixture")
    if set(scenarios) - {r["scenario"] for r in rows}:
        raise ValueError("unknown scenario")
    report = {"label": args.label, "model": args.model, "fixture_sha256": hashlib.sha256(args.fixture.read_bytes()).hexdigest(),
              "provenance": json.loads(args.provenance.read_text()) if args.provenance else None,
              "scope": "Synthetic prescribed-history replay; not original screenshot sessions or a Velox equivalence claim.",
              "cache_condition": "Server state is not reset between waves. First-step means step 0 in this wave, not guaranteed cold; earlier waves can warm later concurrency levels.",
              "history_condition": "agent34 retains six prior screenshots/assistant/tool turns; rolling trimming after step 6 can discard the reusable conversation prefix. image_replace changes only the final image.",
              "ttft_condition": "TTFT is the first nonempty SSE model delta, not an internal token timestamp. Tool parsers may buffer the entire call before that delta.",
              "rate_condition": "post_first_delta_tokens_per_second is unavailable for tool calls and single-chunk prose. For streaming prose it estimates (completion_tokens - 1)/(end - first delta); chunks may contain multiple tokens, so this is not a kernel decode rate.",
              "validation_condition": "Exact screenshot tool arguments and arithmetic are checked. Prose cases check stream integrity and nonempty output, not semantic quality; length-capped outputs are recorded as truncated.",
              "complete": False, "waves": [], "results": []}
    def save():
        temporary = args.output.with_suffix(args.output.suffix + ".tmp")
        temporary.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n")
        temporary.replace(args.output)
    save()
    for scenario in scenarios:
        for degree in degrees:
            selected = [r for r in rows if r["scenario"] == scenario and r["lane"] < degree
                        and (args.steps is None or r["step"] < args.steps)]
            lanes = [sorted((r for r in selected if r["lane"] == lane), key=lambda row: row["step"])
                     for lane in range(degree)]
            if any(not lane for lane in lanes):
                raise ValueError("fixture does not cover every requested lane")
            gate = threading.Barrier(degree)
            def work(lane):
                gate.wait(timeout=60)
                output = []
                for row in lane:
                    item = request(args.url, args.model, row, args.timeout)
                    item["concurrency"] = degree
                    output.append(item)
                    print(json.dumps({k: item.get(k) for k in ("scenario", "concurrency", "lane", "step", "e2e_ms", "ttft_ms", "prompt_tokens", "cached_tokens", "completion_tokens", "failures")}), flush=True)
                return output
            started = time.perf_counter()
            with ThreadPoolExecutor(max_workers=degree) as pool:
                collected = [item for lane in pool.map(work, lanes) for item in lane]
            elapsed = time.perf_counter() - started
            report["results"].extend(collected)
            report["waves"].append({"scenario": scenario, "concurrency": degree, **summarize(collected, elapsed),
                                    "first_step": summarize([r for r in collected if r["step"] == 0]),
                                    "later_steps": summarize([r for r in collected if r["step"] > 0]),
                                    "by_step": {str(step): summarize([r for r in collected if r["step"] == step])
                                                for step in sorted({r["step"] for r in collected})}})
            save()
    report["complete"] = True
    report["passed"] = all(not r["failures"] for r in report["results"])
    save()
    return 0 if report["passed"] else 1


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    prep = sub.add_parser("prepare")
    prep.add_argument("--output", type=evidence_path, required=True)
    prep.add_argument("--steps", type=int, default=30)
    prep.add_argument("--lanes", type=int, default=4)
    prep.add_argument("--max-tokens", type=int, default=128)
    prep.add_argument("--image-width", type=int, default=1344)
    prep.add_argument("--image-height", type=int, default=768)
    replay = sub.add_parser("run")
    replay.add_argument("--fixture", type=Path, required=True)
    replay.add_argument("--output", type=evidence_path, required=True)
    replay.add_argument("--url", default="http://127.0.0.1:5088")
    replay.add_argument("--model", required=True)
    replay.add_argument("--label", required=True)
    replay.add_argument("--provenance", type=Path)
    replay.add_argument("--scenarios", default="short1k,prefill8k,repeat19k,incremental,agent34,image_replace,arithmetic")
    replay.add_argument("--concurrency", default="1,2,4")
    replay.add_argument("--steps", type=int)
    replay.add_argument("--timeout", type=float, default=600)
    args = parser.parse_args()
    return prepare(args) if args.command == "prepare" else run(args)


if __name__ == "__main__":
    raise SystemExit(main())
